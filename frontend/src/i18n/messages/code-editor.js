function nestMessages(messages) {
  const nested = {};
  Object.entries(messages).forEach(([path, value]) => {
    const segments = path.split(".");
    const key = segments.pop();
    const target = segments.reduce((parent, segment) => (parent[segment] ||= {}), nested);
    target[key] = value;
  });
  return nested;
}

